"""Static complete-byte proof for the already-shipped Textual Prism resource."""
from pathlib import Path
import base64,hashlib,json,re,tarfile,sys
raw=Path(sys.argv[1])
textual=Path(sys.argv[2])
artifact=Path(sys.argv[3])
sha=lambda b:hashlib.sha256(b).hexdigest()
bundle=(textual/'Sources/Textual/Internal/Highlighter/Prism/prism-bundle.js').read_bytes()
assert bundle==artifact.read_bytes()
script=(textual/'Scripts/bundle-prism.sh').read_bytes()
meta=json.loads((raw/'prism-npm-metadata.json').read_text())
tar=(raw/'prismjs-1.29.0.tgz').read_bytes()
assert meta['dist']['integrity']=='sha512-'+base64.b64encode(hashlib.sha512(tar).digest()).decode()
assert meta['dist']['shasum']==hashlib.sha1(tar).hexdigest()
with tarfile.open(raw/'prismjs-1.29.0.tgz') as archive:
    files={m.name:archive.extractfile(m).read() for m in archive.getmembers() if m.isfile()}
license_bytes=files['package/LICENSE']
assert license_bytes==(raw/'prism-LICENSE-v1.29.0').read_bytes()
tag=json.loads((raw/'prism-tag-object.json').read_text())
assert tag['object']['type']=='commit' and tag['object']['sha']==meta['gitHead']
assert files['package/prism.js']==(raw/'prism-cdn-default.js').read_bytes()
languages=[x.decode() for x in re.findall(rb'^\s*"([a-z-]+)"',re.search(rb'LANGUAGES=\((.*?)\n\)',script,re.S).group(1),re.M)]
assert len(languages)==57 and len(set(languages))==57
header=bundle.splitlines(keepends=True)[:3]
assert header[0].startswith(b'// Prism.js v1.29.0 - Bundled on ') and header[0].endswith(b'\n')
assert header[1]==b'// Auto-generated by Scripts/bundle-prism.sh - DO NOT EDIT\n' and header[2]==b'\n'
helper=re.search(rb"cat >> .* << 'EOF'\n(.*?)\nEOF",script,re.S).group(1)+b'\n'
ranges=[];cursor=0
def admit(kind,name,data,source):
    global cursor
    assert bundle[cursor:cursor+len(data)]==data,(cursor,name)
    ranges.append({'kind':kind,'name':name,'offset':cursor,'bytes':len(data),'sha256':sha(data),'source':source})
    cursor+=len(data)
admit('textual','header',b''.join(header),'Textual generated header; exact artifact/check-out match; date retained, not regenerated')
admit('prism-distribution','default',(raw/'prism-cdn-default.min.js').read_bytes(),'https://cdnjs.cloudflare.com/ajax/libs/prism/1.29.0/prism.min.js')
admit('separator','newline',b'\n','Textual bundle script')
for lang in languages:
    path='package/components/prism-'+lang+'.min.js'
    admit('prism-component',lang,files[path],path)
    admit('separator','newline',b'\n','Textual bundle script')
admit('textual','helper',helper,"Textual Scripts/bundle-prism.sh heredoc")
assert cursor==len(bundle)
record={'bundle_bytes':len(bundle),'bundle_sha256':sha(bundle),'artifact_path':str(artifact),'textual_source':str(textual),'textual_revision':'01b51875a5406eefc95f52a058cb059e7bc94dc4','prism_version':meta['version'],'prism_commit':tag['object']['sha'],'prism_tag_object':tag['sha'],'npm_integrity_verified':True,'prism_licence_sha256':sha(license_bytes),'cdn_unminified_equals_npm_default':True,'default_source_sections':re.findall(r'Begin (.*)',files['package/prism.js'].decode()),'appended_component_names':languages,'covered_bytes':cursor,'unaccounted_bytes':0,'ranges':ranges,'limits':['Exact CDN distribution match, not reproduced minification. CDN source map returned HTTP404.','Autoloader reference is not plugin inclusion; the default contains file-highlight.','This is resource provenance, not native runtime/network correctness or release approval.','No downloaded JavaScript or bundler was executed.']}
(raw/'bundle-audit.json').write_text(json.dumps(record,indent=2)+'\n')
print(json.dumps({k:v for k,v in record.items() if k not in ['ranges','appended_component_names']},indent=2))
